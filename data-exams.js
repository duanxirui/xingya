  function createExamItems(grade, semester, subject, parts) {
    const allUnits = [...new Set(data.lessons.filter(item => item.grade === grade &&
      item.semester === semester && item.subject === subject && item.textbook !== false)
      .map(item => item.unit))];
    const questions = [];
    for (const [prefix, raw] of parts) {
      const unit = allUnits.find(item => item.startsWith(prefix));
      if (!unit) { console.warn('未找到考试对应教材单元', grade, semester, subject, prefix); continue; }
      raw.trim().split('\n').filter(Boolean).forEach((line, index) => {
        const fields = line.split('|');
        if (fields.length !== 6) { console.warn('考试题配置格式错误', grade, semester, subject, unit, index); return; }
        const [prompt, correct, wrong1, wrong2, wrong3, explanation] = fields;
        const answer = (index + prefix.length) % 4;
        const options = [wrong1, wrong2, wrong3];
        options.splice(answer, 0, correct);
        questions.push({
          id: `exam-g${grade}-s${semester}-${subject}-${prefix}-${index}`,
          grade, semester, subject, unit, lessonTitle: unit,
          prompt, options, answer, explanation, isOriginalExam: true
        });
      });
    }
    return questions;
  }

  data.examQuestions = Object.entries(BANK).flatMap(([key, parts]) => {
    const [grade, semester, subject] = key.split(':');
    return createExamItems(Number(grade), Number(semester), subject, parts);
  });
